import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin, ResolvedConfig } from 'vite';

interface PrecacheEntry {
  url: string;
  sha256: string;
}

async function walk(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  }));
  return files.flat();
}

/** Build from the finished output so dedicated workers and .wasm are included. */
export function offlineShellPlugin(appVersion: string): Plugin {
  let config: ResolvedConfig;
  return {
    name: 'pkm-offline-shell',
    apply: 'build',
    configResolved(resolved) { config = resolved; },
    async writeBundle() {
      const outDirectory = resolve(config.root, config.build.outDir);
      const files = (await walk(outDirectory))
        .filter((path) => !path.endsWith(`${sep}sw.js`))
        .sort();
      const precache: PrecacheEntry[] = await Promise.all(files.map(async (path) => ({
        url: relative(outDirectory, path).split(sep).map(encodeURIComponent).join('/'),
        sha256: createHash('sha256').update(await readFile(path)).digest('hex'),
      })));
      if (!precache.some((entry) => entry.url === 'index.html')) {
        throw new Error('O build não contém index.html para a inicialização offline.');
      }
      const digest = createHash('sha256')
        .update(JSON.stringify(precache))
        .update(serviceWorkerSource([], appVersion))
        .digest('hex').slice(0, 16);
      const version = `${appVersion}+${digest}`;
      await writeFile(join(outDirectory, 'sw.js'), serviceWorkerSource(precache, version), 'utf8');
    },
  };
}

function serviceWorkerSource(precache: PrecacheEntry[], version: string): string {
  return `/* Generated by pkm-offline-shell. The cache contains application files, never SQL data. */
'use strict';
const VERSION = ${JSON.stringify(version)};
const scope = self.registration.scope;
const CACHE_PREFIX = 'pkm-offline-shell:' + encodeURIComponent(new URL(scope).pathname) + ':';
const CACHE_NAME = CACHE_PREFIX + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const urls = PRECACHE.map(entry => new URL(entry.url, scope).href);
const staticUrls = new Set(urls);
const indexUrl = new URL('index.html', scope).href;

async function cacheIsComplete() {
  if (!(await caches.has(CACHE_NAME))) return false;
  const cache = await caches.open(CACHE_NAME);
  // Vite may serve Vary: Origin. These public, hash-verified static files have
  // identical content with or without the module loader's Origin header.
  const matches = await Promise.all(urls.map(url => cache.match(url, { ignoreVary: true })));
  return matches.every(response => response && response.ok);
}

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    try {
      await Promise.all(PRECACHE.map(async entry => {
        const url = new URL(entry.url, scope).href;
        const response = await fetch(new Request(url, { cache: 'reload', credentials: 'same-origin' }));
        if (!response.ok) throw new Error('Arquivo indisponível no preparo offline.');
        const digest = await crypto.subtle.digest('SHA-256', await response.clone().arrayBuffer());
        const sha256 = Array.from(new Uint8Array(digest), byte => byte.toString(16).padStart(2, '0')).join('');
        if (sha256 !== entry.sha256) throw new Error('Arquivo incompatível com esta versão.');
        await cache.put(url, response);
      }));
      if (!(await cacheIsComplete())) throw new Error('Cache offline incompleto.');
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
    // A new version intentionally stays waiting until ACTIVATE is requested.
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    if (!(await cacheIsComplete())) throw new Error('Cache offline incompleto.');
    // Preserve previous versions: an older open tab may still need its worker or WASM.
    // No origin-wide cache deletion is allowed here.
    await self.clients.claim();
    const clients = await self.clients.matchAll({ type: 'window' });
    for (const client of clients) client.postMessage({ type: 'PKM_CACHE_READY', version: VERSION });
  })());
});

self.addEventListener('message', event => {
  if (event.data?.type === 'STATUS') {
    event.waitUntil((async () => {
      const ready = await cacheIsComplete();
      event.ports[0]?.postMessage({ type: 'STATUS', ready, version: VERSION });
    })());
  } else if (event.data?.type === 'ACTIVATE') {
    event.waitUntil(self.skipWaiting());
  }
});

async function findCached(request) {
  const current = await caches.open(CACHE_NAME);
  if (staticUrls.has(request.url)) {
    const response = await current.match(request, { ignoreVary: true });
    if (response) return response;
  }
  const names = await caches.keys();
  for (const name of names) {
    if (name !== CACHE_NAME && name.startsWith(CACHE_PREFIX)) {
      const priorCache = await caches.open(name);
      // Previous-version caches only contain their enumerated precache files.
      // Match the exact URL: do not broaden paths, queries, origin or scope.
      const entries = await priorCache.keys();
      if (entries.some(entry => entry.method === 'GET' && entry.url === request.url)) {
        const prior = await priorCache.match(request, { ignoreVary: true });
        if (prior) return prior;
      }
    }
  }
  return undefined;
}

self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.href.startsWith(scope)) return;
  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      const response = await (await caches.open(CACHE_NAME)).match(indexUrl, { ignoreVary: true });
      return response || fetch(request);
    })());
  } else {
    event.respondWith((async () => (await findCached(request)) || fetch(request))());
  }
});
`;
}
